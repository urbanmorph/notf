#!/usr/bin/env python3
"""Build the India outline used by the city maps on /communities/ and /catalog/.

Source: LGD state and Union Territory boundaries (Local Government Directory,
via bharatlas `lgd_states`, CC0/CC-BY-4.0). The official boundaries matter here:
other open outlines draw Jammu & Kashmir and Ladakh differently.

    curl -o /tmp/LGD_States.geojson \\
      https://pub-0429b8e3b5a946e69ea007df844a6f1c.r2.dev/admin/states/LGD_States.geojson
    python3 scripts/build-india-outline.py /tmp/LGD_States.geojson \\
      > website/public/assets/js/india-outline.js

Writes window.INDIA_OUTLINE = {bbox, width, height, d}: one SVG path of every
state, in the projection of assets/js/map-projection.js.
"""

import json
import sys

from outline_lib import projector, ring_path, simplify_ring

WIDTH = 600
TOLERANCE = 0.04  # degrees (~4 km): state shapes stay recognisable at 600 px
MIN_POINTS = 4  # rings that simplify below this (tiny islands) are dropped


def rings_of(geometry):
    if geometry["type"] == "Polygon":
        return geometry["coordinates"][:1]
    return [poly[0] for poly in geometry["coordinates"]]


def main(src):
    features = json.load(open(src))["features"]
    rings = [r for f in features for r in rings_of(f["geometry"])]
    project, bbox, height = projector(rings, WIDTH, pad=0.5)
    paths = []
    for ring in rings:
        xy = [project(lon, lat) for lon, lat in simplify_ring(ring, TOLERANCE)]
        deduped = [p for i, p in enumerate(xy) if i == 0 or p != xy[i - 1]]
        if len(deduped) >= MIN_POINTS:
            paths.append(ring_path(deduped))
    outline = {
        "bbox": [round(v, 4) for v in bbox],
        "width": WIDTH,
        "height": height,
        "d": "".join(paths),
    }
    print("// Generated by scripts/build-india-outline.py from LGD state boundaries. Do not edit.")
    print(f"window.INDIA_OUTLINE = {json.dumps(outline, separators=(',', ':'))};")


if __name__ == "__main__":
    main(sys.argv[1])
